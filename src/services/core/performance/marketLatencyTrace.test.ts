import assert from 'node:assert/strict';
import { MarketLatencyTrace, type MarketLatencySample } from './marketLatencyTrace';
const trace = new MarketLatencyTrace();
const samples: MarketLatencySample[] = [];
trace.setSink(sample => samples.push(sample));
trace.setSampleEvery(4);
assert.equal(trace.measure('fyers:NSE:TRACE:5m', 4, 'canonical', () => 42), 42);
trace.record('fyers:NSE:TRACE:5m', 4, 'feed', 10, 12);
trace.record('fyers:NSE:TRACE:5m', 5, 'patch', 12, 13);
assert.equal(samples.length, 2);
assert.deepEqual(samples.map(sample => sample.stage), ['canonical', 'feed']);
assert.equal(samples[0]?.durationMs, samples[0]!.endedAt - samples[0]!.startedAt);
assert.equal(samples[1]?.sequence, 4);
trace.setSink(() => { throw new Error('diagnostic failure'); });
assert.doesNotThrow(() => trace.record('key', 8, 'paint', 20, 22));
trace.setSink(undefined);
let ran = false;
assert.equal(trace.measure('key', 8, 'compute', () => { ran = true; return 'ok'; }), 'ok');
assert.equal(ran, true);
assert.equal(await trace.measureAsync('key', 8, 'compute', async () => 7), 7);
console.log('MARKET_LATENCY_TRACE_CONTRACT_OK');
