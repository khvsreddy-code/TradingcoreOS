import { updateCoreSpiritAstNodeMetadata, type CoreSpiritAst, type CoreSpiritAstNode, type CoreSpiritFunctionDeclarationNode } from './ast';

export type CoreSpiritFunctionDesugarDiagnostic = Readonly<{
  severity:'error'; code:string; message:string; start?:number; end?:number; line?:number; column?:number;
}>;
export type CoreSpiritFunctionDesugarResult = Readonly<{
  ast:CoreSpiritAst; diagnostics:readonly CoreSpiritFunctionDesugarDiagnostic[];
}>;
type Environment=ReadonlyMap<string,CoreSpiritAstNode>;

const EFFECTFUL_CALLS=new Set([
  'plot','plotshape','plotchar','plotarrow','plotcandle','plotbar','show',
  'entry','exit','buy','sell','order','orderintent','alert','alertcondition',
  'webhook','signal','market','timeframe','series','model','dataset','hmmfit',
  'automation','strategy','request',
]);
const EFFECTFUL_METHODS=new Set([
  'push','pop','shift','unshift','set','delete','submit','cancel','send',
  'entry','exit','buy','sell','alert','webhook','route',
]);

function report(out:CoreSpiritFunctionDesugarDiagnostic[],node:CoreSpiritAstNode,code:string,message:string):void {
  out.push({severity:'error',code,message,start:node.span?.start,end:node.span?.end,line:node.span?.line,column:node.span?.column});
}
function clone(node:CoreSpiritAstNode):CoreSpiritAstNode {
  switch(node.type){
    case 'number':case 'string':case 'boolean':case 'null':case 'identifier':return {...node};
    case 'unary':return {...node,operand:clone(node.operand)};
    case 'binary':return {...node,left:clone(node.left),right:clone(node.right)};
    case 'conditional':return {...node,condition:clone(node.condition),whenTrue:clone(node.whenTrue),whenFalse:clone(node.whenFalse)};
    case 'call':return {...node,args:node.args.map(clone)};
    case 'member':return {...node,target:clone(node.target)};
    case 'memberCall':return {...node,target:clone(node.target),args:node.args.map(clone)};
    case 'index':return {...node,target:clone(node.target),index:clone(node.index)};
    case 'arrayLiteral':return {...node,elements:node.elements.map(clone)};
    case 'mapLiteral':return {...node,entries:node.entries.map(entry=>({...entry,value:clone(entry.value)}))};
    default:return {...node} as CoreSpiritAstNode;
  }
}
function effect(node:CoreSpiritAstNode):string|undefined {
  switch(node.type){
    case 'call':
      if(EFFECTFUL_CALLS.has(node.name.toLowerCase()))return node.name;
      for(const arg of node.args){const e=effect(arg);if(e)return e;}
      return undefined;
    case 'memberCall':{
      const target=node.target.type==='identifier'?node.target.name.toLowerCase():'';
      if(EFFECTFUL_METHODS.has(node.member.toLowerCase())||['request','strategy','automation','alert'].includes(target))return target?target+'.'+node.member:node.member;
      const targetEffect=effect(node.target);if(targetEffect)return targetEffect;
      for(const arg of node.args){const e=effect(arg);if(e)return e;}
      return undefined;
    }
    case 'unary':return effect(node.operand);
    case 'binary':return effect(node.left)??effect(node.right);
    case 'conditional':return effect(node.condition)??effect(node.whenTrue)??effect(node.whenFalse);
    case 'member':return effect(node.target);
    case 'index':return effect(node.target)??effect(node.index);
    case 'arrayLiteral':
      for(const item of node.elements){const e=effect(item);if(e)return e;}
      return undefined;
    case 'mapLiteral':
      for(const entry of node.entries){const e=effect(entry.value);if(e)return e;}
      return undefined;
    default:return undefined;
  }
}

/**
 * Converts the bounded pure-function subset from function AST into ordinary
 * expression AST consumed by the canonical semantic analyser and IR generator.
 * No source text is tokenized, parsed, replaced or regenerated by this pass.
 */
export function desugarCoreSpiritFunctions(ast:CoreSpiritAst):CoreSpiritFunctionDesugarResult {
  const diagnostics:CoreSpiritFunctionDesugarDiagnostic[]=[];
  const functions=new Map<string,CoreSpiritFunctionDeclarationNode>();
  for(const node of ast.body){
    if(node.type!=='functionDeclaration')continue;
    if(functions.has(node.name)){report(diagnostics,node,'FUNCTION_DUPLICATE',`Function '${node.name}' is declared more than once.`);continue;}
    const seen=new Set<string>();
    for(const parameter of node.parameters){
      if(seen.has(parameter.name))report(diagnostics,node,'FUNCTION_DUPLICATE_PARAMETER',`Function '${node.name}' declares parameter '${parameter.name}' more than once.`);
      seen.add(parameter.name);
    }
    functions.set(node.name,node);
  }

  const expand=(node:CoreSpiritAstNode,env:Environment,stack:readonly string[],depth:number):CoreSpiritAstNode=>{
    if(depth>64){report(diagnostics,node,'FUNCTION_EXPANSION_DEPTH','Function AST expansion exceeded 64 nested nodes.');return clone(node);}
    if(node.type==='identifier'){
      const value=env.get(node.name);
      return value?clone(value):clone(node);
    }
    if(node.type==='call'){
      const args=node.args.map(arg=>expand(arg,env,stack,depth+1));
      const definition=functions.get(node.name);
      if(!definition)return {...node,args};
      if(stack.includes(node.name)){
        report(diagnostics,node,'FUNCTION_RECURSION',`Recursive function call '${[...stack,node.name].join(' -> ')}' is unsupported in the pure expression-function tier.`);
        return {...node,args};
      }
      if(stack.length>=32){
        report(diagnostics,node,'FUNCTION_EXPANSION_DEPTH',`Function expansion exceeded 32 nested calls at '${node.name}'.`);
        return {...node,args};
      }
      if(args.length!==definition.parameters.length){
        report(diagnostics,node,'FUNCTION_ARGUMENT_COUNT',`Function '${node.name}' expects ${definition.parameters.length} arguments but received ${args.length}.`);
        return {...node,args};
      }
      const bindings=new Map<string,CoreSpiritAstNode>();
      definition.parameters.forEach((parameter,index)=>{
        const argument=clone(args[index]!);
        updateCoreSpiritAstNodeMetadata(argument,{expectedTypes:[...(argument.metadata?.expectedTypes??[]),parameter.declaredType]});
        bindings.set(parameter.name,argument);
      });
      let result:CoreSpiritAstNode|undefined;
      let returned=false;
      for(const statement of definition.body){
        if(statement.type==='let'){
          if(returned){report(diagnostics,statement,'FUNCTION_STATEMENT_AFTER_RETURN',`Function '${node.name}' has a local declaration after return.`);continue;}
          if(bindings.has(statement.name)){report(diagnostics,statement,'FUNCTION_DUPLICATE_LOCAL',`Function '${node.name}' redeclares '${statement.name}'.`);continue;}
          const foundEffect=effect(statement.expression);
          if(foundEffect)report(diagnostics,statement,'FUNCTION_SIDE_EFFECT',`Pure function '${node.name}' cannot perform effectful operation '${foundEffect}'.`);
          bindings.set(statement.name,expand(statement.expression,bindings,[...stack,node.name],depth+1));
          continue;
        }
        if(statement.type==='return'){
          if(returned){report(diagnostics,statement,'FUNCTION_MULTIPLE_RETURNS',`Function '${node.name}' must contain exactly one terminal return.`);continue;}
          returned=true;
          const foundEffect=effect(statement.expression);
          if(foundEffect)report(diagnostics,statement,'FUNCTION_SIDE_EFFECT',`Pure function '${node.name}' cannot return effectful operation '${foundEffect}'.`);
          result=expand(statement.expression,bindings,[...stack,node.name],depth+1);
          continue;
        }
        if(statement.type==='expressionStatement'){
          const foundEffect=effect(statement.expression);
          if(foundEffect) report(diagnostics,statement,'FUNCTION_SIDE_EFFECT',`Pure function '${node.name}' cannot perform effectful operation '${foundEffect}'.`);
          else report(diagnostics,statement,'FUNCTION_UNSUPPORTED_BODY',`Function '${node.name}' does not support expression statements in its body.`);
          continue;
        }
        report(diagnostics,statement,'FUNCTION_UNSUPPORTED_BODY',`Function '${node.name}' currently supports local let/const expressions followed by one return; '${statement.type}' is unsupported.`);
      }
      if(!result){report(diagnostics,definition,'FUNCTION_MISSING_RETURN',`Function '${node.name}' must end with one return expression.`);return {...node,args};}
      updateCoreSpiritAstNodeMetadata(result,{expectedTypes:[...(result.metadata?.expectedTypes??[]),definition.returnType]});
      return result;
    }
    switch(node.type){
      case 'unary':return {...node,operand:expand(node.operand,env,stack,depth+1)};
      case 'binary':return {...node,left:expand(node.left,env,stack,depth+1),right:expand(node.right,env,stack,depth+1)};
       case 'conditional':return {...node,condition:expand(node.condition,env,stack,depth+1),whenTrue:expand(node.whenTrue,env,stack,depth+1),whenFalse:expand(node.whenFalse,env,stack,depth+1)};
      case 'member':return {...node,target:expand(node.target,env,stack,depth+1)};
      case 'memberCall':return {...node,target:expand(node.target,env,stack,depth+1),args:node.args.map(arg=>expand(arg,env,stack,depth+1))};
      case 'index':return {...node,target:expand(node.target,env,stack,depth+1),index:expand(node.index,env,stack,depth+1)};
      case 'arrayLiteral':return {...node,elements:node.elements.map(item=>expand(item,env,stack,depth+1))};
      case 'mapLiteral':return {...node,entries:node.entries.map(entry=>({...entry,value:expand(entry.value,env,stack,depth+1)}))};
      case 'number':case 'string':case 'boolean':case 'null':return {...node};
      default:report(diagnostics,node,'FUNCTION_INVALID_EXPRESSION',`Unsupported expression node '${node.type}' in a pure function.`);return clone(node);
    }
  };

  const transformStatements=(nodes:readonly CoreSpiritAstNode[],nested=false):CoreSpiritAstNode[]=>{
    const output:CoreSpiritAstNode[]=[];
    for(const node of nodes){
      switch(node.type){
        case 'functionDeclaration':
          if(nested)report(diagnostics,node,'FUNCTION_NESTED_DECLARATION','Nested function declarations are unsupported.');
          break;
        case 'return':report(diagnostics,node,'FUNCTION_RETURN_OUTSIDE_FUNCTION','return is only valid inside a function.');break;
        case 'program':output.push({...node,body:transformStatements(node.body,nested)});break;
        case 'let':case 'assignment':case 'expressionStatement':
          output.push({...node,expression:expand(node.expression,new Map(),[],0)});break;
        case 'if':
          output.push({...node,condition:expand(node.condition,new Map(),[],0),thenBranch:transformStatements(node.thenBranch,true),elseBranch:node.elseBranch?transformStatements(node.elseBranch,true):undefined});break;
        case 'onEvent':output.push({...node,body:transformStatements(node.body,true)});break;
        case 'while':output.push({...node,condition:expand(node.condition,new Map(),[],0),body:transformStatements(node.body,true)});break;
        case 'forEach':output.push({...node,iterable:expand(node.iterable,new Map(),[],0),body:transformStatements(node.body,true)});break;
        case 'typeDeclaration':case 'break':case 'continue':output.push({...node});break;
        default:report(diagnostics,node,'FUNCTION_UNSUPPORTED_STATEMENT',`Unsupported statement '${node.type}' in CoreSpirit function lowering.`);break;
      }
    }
    return output;
  };
  return {ast:{...ast,body:transformStatements(ast.body,false)},diagnostics};
}
