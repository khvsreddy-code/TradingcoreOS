export type CoreSpiritLibraryNamespace =
  | 'core' | 'market' | 'series' | 'math' | 'stats' | 'time' | 'timeframe' | 'structure'
  | 'volatility' | 'liquidity' | 'probability' | 'regime' | 'model' | 'ml' | 'prediction'
