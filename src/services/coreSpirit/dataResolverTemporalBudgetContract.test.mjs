import assert from 'node:assert/strict';
import {CoreSpiritDataResolverService} from './dataResolver.ts';
const asOf=Date.parse('2025-01-01T00:05:00Z');
let revision=1;
const memo=new Map();
const context=()=>({symbol:'NSE:NIFTY50-INDEX',timeframe:'5m',mode:'historical'});
const bar=()=>({timestamp:new Date(asOf).toISOString()});
let snapshot={value:100,source:'fixture',symbol:'NSE:NIFTY50-INDEX',timeframe:'5m',timestamp:asOf-300000,closeTimestamp:asOf,state:'confirmed',confirmationPhase:'confirmed'};
const resolver=new CoreSpiritDataResolverService({requestAt:()=>snapshot},context,bar,Date.parse.bind(Date),memo,()=>revision,2);
assert.equal(resolver.resolveValue('NSE:NIFTY50-INDEX','5m','close',0),100);
assert.equal(resolver.resolveValue('NSE:NIFTY50-INDEX','5m','close',0),100,'same request identity is deduplicated');
snapshot={...snapshot,timestamp:asOf,closeTimestamp:asOf+1};
assert.equal(resolver.resolveValue('NSE:NIFTY50-INDEX','5m','close',0,1),null,'a higher-timeframe candle whose close is in the future is rejected');
snapshot={...snapshot,timestamp:asOf-1000,closeTimestamp:asOf,state:'developing',confirmationPhase:'developing'};
assert.equal(resolver.resolveValue('NSE:NIFTY50-INDEX','5m','close',0,2),null,'developing snapshots are rejected in historical mode');
assert.equal(resolver.uniqueRequestCount,2);
assert.equal(resolver.resolveValue('NSE:BANKNIFTY-INDEX','5m','close',0),null,'unique request budget fails closed');
revision++;
snapshot={value:200,source:'fixture',symbol:'NSE:BANKNIFTY-INDEX',timeframe:'5m',timestamp:asOf-300000,closeTimestamp:asOf,state:'confirmed',confirmationPhase:'confirmed'};
assert.equal(resolver.resolveValue('NSE:BANKNIFTY-INDEX','5m','close',0),200,'new data revision opens a fresh request budget');
console.log('CORESPIRIT_DATA_REQUEST_TEMPORAL_BUDGET_CONTRACT_OK');