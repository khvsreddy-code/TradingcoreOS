assert(schema.includes("{ all: readonly IndicatorSettingCondition[] }"), 'AND dependency groups missing');
assert(schema.includes("{ any: readonly IndicatorSettingCondition[] }"), 'OR dependency groups missing');
assert(schema.includes("{ not: IndicatorSettingCondition }"), 'NOT dependency groups missing');
assert(schema.includes("condition.path === ownerPath"), 'self-dependency guard missing');
assert(schema.includes('fieldByPath'), 'typed condition target validation missing');
assert(schema.includes('numeric dependency'), 'numeric dependency domain validation missing');
assert(schema.includes("depth > 8"), 'conditional dependency depth bound missing');
assert(schema.includes('length > 16'), 'conditional group size bound missing');
assert(schema.includes("return false;"), 'malformed conditional evaluator must fail closed');
assert(schema.includes('Array.isArray(condition.values) && condition.values.length > 0'), 'membership evaluator must fail closed on malformed values');
assert(schema.includes("parametersFromSections(sections)"), 'parameter ABI is not derived from declared Inputs fields');
assert(panel.includes('resolveIndicatorParameterState') && panel.includes('parameterState.visible') && panel.includes('parameterState.enabled'), 'panel is not using the canonical resolved conditional state');
assert(schema.includes('v1/v2 custom publications remain readable'), 'legacy migration documentation missing');
