import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = path => fs.readFileSync(new URL(path, import.meta.url), 'utf8');
const live = read('./LiveTradingWorkspace.tsx');
const dock = read('./components/corespirit/CoreSpiritDock.tsx');
const smc = read('./services/coreSpirit/luxAlgoSmcCoreSource.ts');
const chrome = read('./services/core/chart/tcoVelaChrome.ts');
const terminal = read('./services/core/chart/tcoVelaTerminal.ts');
const cell = read('../vendor/vela/src/workspace/ChartCell.ts');
const contributions = read('../vendor/vela/src/widget/contributions.ts');

assert.match(live, /aria-label="Toggle Watchlist panel"/, 'right rail exposes the Watchlist control');
assert.match(live, /aria-label="Toggle CoreSpirit coding terminal"/, 'right rail exposes the CoreSpirit control');
assert.match(live, /corespirit-rail-flame/, 'right-side button uses the custom fire-and-cogwheel icon');
assert.match(live, /right-11/, 'chart host reserves space for the right rail');
assert.match(live, /activeCell\\.addExternalIndicator\\(/, 'Add to Chart uses Vela external-indicator lifecycle on the active chart');
assert.match(live, /__TCO_ADD_CORESPIRIT_TO_CHART__/, 'active-chart bridge is installed and disposed with the workspace');
assert.match(chrome, /createRoot\\(body\\)/, 'CoreSpirit React terminal is mounted inside Vela panel body');
assert.match(chrome, /embedded: true/, 'CoreSpirit is docked rather than rendered as an overlay popup');
assert.match(chrome, /ctx\\.togglePanel\\('tco\\.corespirit-code', false\\)/, 'terminal close button closes the Vela side panel');
assert.match(chrome, /onAddToChart: async/, 'embedded terminal uses the active-chart bridge for Add to Chart');
assert.match(dock, /compileCoreSpiritSourceOffThread/, 'CoreSpirit source compiles through its worker pipeline');
assert.match(dock, /CORESPIRIT_LUXALGO_SMC_SOURCE/, 'the editor uses the converted SMC script as its default');
assert.match(smc, /input swingLength: int = 50 min=10 max=100/, 'SMC swing lookback defaults to the Pine script 50-bar setting');
assert.match(smc, /input internalLength: int = 5 min=2 max=20/, 'SMC internal structure defaults to five bars');
assert.match(smc, /Swing CHoCH|Swing BOS/, 'converted source emits swing structure labels');
assert.match(smc, /Internal CHoCH|Internal BOS/, 'converted source emits internal structure labels');
assert.match(smc, /showOrderBlockZones/, 'converted source exposes the provisional order-block zone option');
assert.match(smc, /showFairValueGaps/, 'converted source exposes FVG visibility');
assert.doesNotMatch(smc, /lookahead|request\\.security/, 'initial conversion does not introduce future-data or MTF lookahead');
assert.match(dock, /saveUserIndicatorDraft/, 'Save creates a versioned cloud draft');
assert.match(dock, /\\.from\\('corespirit_script_versions'\\)/, 'version history is read from the script version table');
assert.match(dock, /onClick=\\{\\(\\) => void rename\\(\\)\\}/, 'rename button is wired');
assert.match(dock, /publishUserIndicator/, 'Publish uses the existing publication service');
assert.match(dock, /onAddToChart\\(cleanName, source\\)/, 'Add to Chart calls the active-chart callback');
assert.match(dock, /Fullscreen CoreSpirit editor/, 'terminal provides a fullscreen control');
assert.match(dock, /Minimize CoreSpirit editor/, 'terminal provides a minimize control');
assert.match(dock, /Close CoreSpirit terminal/, 'terminal provides a close control');
assert.match(cell, /addExternalIndicator\\(entry: ExternalIndicatorEntry\\)/, 'Vela external-indicator entry point remains available');
assert.match(contributions, /export interface ExternalIndicatorEntry/, 'dock uses Vela public external-indicator entry type');
for (const label of ['Compile', 'Save', 'Publish', 'Add to chart', 'Rename']) assert.ok(dock.includes(label), label + ' action visible');
assert.doesNotMatch(terminal, /'tco\\.watchlist',/, 'Watchlist must be removed from the topbar action list');
assert.doesNotMatch(terminal, /'tco\\.corespirit-code',/, 'CoreSpirit must be removed from the topbar action list');
console.log('CORESPIRIT_DOCK_CONTRACT_OK');
