import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';

const root=process.cwd();
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const route=read('src/server/routes/coreSpirit-copilot.routes.ts');
const server=read('server.ts');
const env=read('.env.example');
const editor=read('src/pages/CoreSpiritEditorPage.tsx');

assert.match(route,/coreSpiritCopilotRoutes\.use\(requireUser\)/,'Copilot API must authenticate');
assert.match(route,/MAX_PROMPT_CHARS=4_000/,'Copilot prompts must be bounded');
assert.match(route,/MAX_SOURCE_BYTES=64\*1024/,'source sent to the model must be bounded');
assert.match(route,/createRateLimiter\(\{/,'Copilot must use the shared API rate limiter');
assert.match(route,/windowMs:60_000/,'Copilot limiter must use a one-minute window');
assert.match(route,/max:10/,'Copilot needs a 10-request per-minute limit');
assert.match(route,/tradingCoreUserId/,'Copilot rate limit keys must be user-scoped');
assert.match(route,/process\.env\.GEMINI_API_KEY/,'provider secret must remain server-side');
assert.match(route,/responseFormat:\s*\{/,'Copilot must use Gemini structured JSON output');
assert.match(route,/thinkingConfig:\{thinkingLevel:'low'\}/,'Copilot should use the low-latency Gemini thinking configuration');
assert.doesNotMatch(route,/temperature\s*:/,'Gemini 3.x request must not include unsupported sampling parameters');
assert.doesNotMatch(route,/VITE_[A-Z_]*GEMINI|VITE_[A-Z_]*GOOGLE/,'provider key must never be read from a browser-visible environment variable');
assert.match(route,/compileCoreSpirit\(generated\.source,'corespirit-editor'/,'generated source must go through the canonical compiler with the same artifact identity as the editor');
assert.match(editor,/copilotServerArtifactHashRef\.current=payload\.validation\?\.artifactHash/,'the Copilot response artifact hash must be pinned to its exact draft');
assert.match(editor,/copilotReplayPassRef\.current!==true/,'Copilot Run must fail closed until the exact artifact passes replay');
assert.match(editor,/requestedEditorVersion/,'late Copilot responses must not overwrite edits made while generation is in flight');
assert.match(editor,/generationRequest!==copilotGenerationRef\.current/,'overlapping Copilot requests and stale replay results must be discarded');
assert.match(editor,/replayGateMatches\(replayGate,source,copilotServerArtifactHashRef\.current,targetAtStart\)/,'Copilot replay approval must be tied to the same source, artifact, and active chart');
assert.match(editor,/replayContextStillCurrent/,'replay approval must be invalidated if the active chart/history boundary changes during preflight');
assert.match(editor,/copilotReplayGateRef\.current=replayPassed\?/,'only a successful replay may issue a context-bound approval gate');
assert.match(editor,/activeAfterGeneration/,'Copilot generation must remain attached to the chart context supplied to the model');
assert.match(editor,/copilotReplayPassRef\.current=replayPassed/,'replay gate must be tied to the completed replay result');
assert.match(editor,/setCopilotStatus\('blocked'\)/,'missing history or replay infrastructure failure must block Copilot Run');
assert.doesNotMatch(editor,/copilotReplayPassRef\.current=false;[\s\S]{0,400}setCopilotStatus\('ready'\)/,'a missing replay result must never be represented as replay-ready');
assert.match(editor,/COPILOT_ARTIFACT_HASH_MISMATCH/,'server/local artifact identity mismatches must block Copilot Run');
const worker=read('src/services/coreSpirit/coreSpiritCompiler.worker.ts');
const client=read('src/services/coreSpirit/coreSpiritCompilerClient.ts');
assert.match(worker,/type==='replayPreview'/,'validated Copilot artifacts should get an isolated replay preflight');
assert.match(worker,/executeIrReadOnly/,'Copilot replay must suppress external effects');
assert.match(worker,/message\.bars\.length>3000/,'replay preflight must be bounded to 3,000 bars');
assert.match(client,/previewCoreSpiritArtifactOffThread/,'replay must execute through the compiler worker client');
assert.match(route,/validateExecutableArtifact\(compiled\.artifact\)/,'generated artifact must pass integrity validation');
assert.match(route,/createCoreSpiritSandbox\(\{layer:'script',target:'chart'\}\)/,'generated code must be checked against chart-layer grants');
assert.match(route,/validateCoreScriptCapabilitiesAgainstSandbox/,'required capabilities must be checked against sandbox grants');
assert.match(route,/validateCoreSpiritSandboxArchitecture\(\)/,'forbidden capabilities must be checked');
assert.doesNotMatch(route,/runCoreSpiritInWorker|coreSpiritWorkerPool|executeCoreSpirit\(|\.executeIr\(/,'Copilot endpoint must never execute generated source');
assert.match(route,/nextStep:'Review the draft/,'response must tell the user the draft is never auto-run');
assert.match(server,/app\.use\('\/api\/corespirit\/copilot', coreSpiritCopilotRoutes\)/,'server must mount Copilot endpoint');
assert.match(env,/^GEMINI_API_KEY=/m,'server configuration must document the private provider key');
assert.match(editor,/\/api\/corespirit\/copilot\/generate/,'editor must use the authenticated server endpoint');
assert.match(editor,/Authorization:/,'editor must send an authorization header');
assert.match(editor,/session\.access_token/,'editor must send the signed-in access token');
assert.match(editor,/Nothing runs automatically/,'UI must state that AI output is not executed automatically');
assert.match(editor,/must then pass a bounded read-only historical replay before Run/,'UI must explain the mandatory replay gate');
const start=editor.indexOf('const generateCopilotDraft=async()=>{');
const end=editor.indexOf('const save = async () =>',start);
assert.ok(start>=0&&end>start,'Copilot handler must be present');
assert.doesNotMatch(editor.slice(start,end),/runOnChart\(|runActiveChart\(/,'Copilot generation must not auto-run generated code');
