import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const vercel=JSON.parse(fs.readFileSync(path.join(root,'vercel.json'),'utf8'));
const rewrites=vercel.rewrites||[];
if (!rewrites.some((r)=>r.source==='/api/:path*'&&r.destination?.service==='api')) throw new Error('API catch-all must route to the API service');
const spaFallback=rewrites.find((r)=>r.source==='/(.*)'&&r.destination?.service==='web');
if (!spaFallback) throw new Error('SPA catch-all must route to the web service');
const webSpaRewrite=(vercel.services?.web?.rewrites||[]).find((route)=>route.source==='/(.*)'&&route.destination==='/index.html');
if (!webSpaRewrite) throw new Error('Web service must rewrite SPA page routes to /index.html so OAuth callbacks and deep links do not return Vercel 404s');
const appSource=fs.readFileSync(path.join(root,'src/App.tsx'),'utf8');
if (!appSource.includes("pathname.startsWith('/auth/broker-callback')")) throw new Error('Broker OAuth callback path is not recognized by App');
const workspaceShell=fs.readFileSync(path.join(root,'src/appShells/TradingWorkspaceShell.tsx'),'utf8');
if (!workspaceShell.includes("route === '/corespirit'")) throw new Error('CoreSpirit route is missing from TradingWorkspaceShell');
console.log('STAGE89_SPA_ROUTE_CONTRACT_OK');
