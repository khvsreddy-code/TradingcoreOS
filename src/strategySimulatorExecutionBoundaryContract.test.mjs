import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL(p,import.meta.url),'utf8');
const simulator=read('./services/core/replay/strategySimulator.ts');
const engine=read('./services/engine/TradingEngine.ts');
assert.ok(simulator.includes("executionAuthority:'simulation-only'"));
assert.ok(simulator.includes("liveBrokerOrdersSubmitted:false"));
assert.ok(simulator.includes('intrabarPolicy'));
assert.ok(simulator.includes('maxGrossExposureMultiple'));
assert.ok(simulator.includes("i.type==='stop-limit'"));
assert.ok(!/from ['"].*TradingEngine/.test(simulator),'simulator must not import the live engine');
assert.ok(!/\.placeOrder\s*\(/.test(simulator),'simulator must not call live broker methods');
assert.ok(/public async placeOrder\(order: OrderRequest\)/.test(engine),'live broker submission is confined to TradingEngine');
console.log('STRATEGY_SIMULATION_LIVE_EXECUTION_BOUNDARY_OK');
